OcrResult TimestampOcr::recognizeFromYPlane(const uint8_t* yPlane,
                                             int width,
                                             int height,
                                             int yStride,
                                             int tzOffsetSec) {
    OcrResult res;
    if (!yPlane || width < 640 || height < 360 || yStride < width) {
        return res;
    }

    // 14 个数字在 "YYYY/MM/DD HH:MM:SS" 中的槽位索引
    constexpr std::array<int, 14> kDigitSlots = {0, 1, 2, 3, 5, 6, 8, 9, 11, 12, 14, 15, 17, 18};
    const auto& tpls = getTemplates();

    int baseX = 0, baseY = 0, bw = 0, bh = 0;
    double stepX = 0.0;
    std::array<int, 5> dxSearch{};
    int dxCount = 0;

    if (width == 2304 && height == 1296) {
        baseX = 123; baseY = 64; bw = 24; bh = 32; stepX = 34.0;
        dxSearch = {-3, 0, 3, 0, 0}; dxCount = 3;
    } else if (width == 3840 && height == 2160) {
        baseX = 183; baseY = 80; bw = 42; bh = 59; stepX = 60.0;
        dxSearch = {-5, -2, 0, 2, 5}; dxCount = 5;
    } else {
        baseX = static_cast<int>(std::lround(width * 0.0477));
        baseY = static_cast<int>(std::lround(height * 0.0370));
        bw = std::max(12, static_cast<int>(std::lround(width * 0.0109)));
        bh = std::max(18, static_cast<int>(std::lround(height * 0.0273)));
        stepX = width * 0.0156;
        dxSearch = {-3, 0, 3, 0, 0}; dxCount = 3;
    }
    constexpr std::array<int, 3> dySearch = {-2, 0, 2};

    QString digits;
    digits.reserve(14);
    double sumConf = 0.0;
    double minConf = 1.0;

    for (int slot : kDigitSlots) {
        const int x0 = baseX + static_cast<int>(std::lround(slot * stepX));
        const int y0 = baseY;
        int bestDigit = -1;
        double bestScore = -1.0;

        for (int dy : dySearch) {
            for (int di = 0; di < dxCount; ++di) {
                const int x = x0 + dxSearch[di];
                const int y = y0 + dy;
                if (x < 0 || y < 0 || x + bw > width || y + bh > height) continue;
                for (int d = 0; d < 10; ++d) {
                    const float sc = scorePatch(yPlane, yStride, x, y, bw, bh, tpls.tpl[d]);
                    if (sc > bestScore) {
                        bestScore = sc;
                        bestDigit = d;
                    }
                }
            }
        }

        if (bestDigit < 0) return res;
        digits.append(QChar('0' + bestDigit));
        sumConf += bestScore;
        minConf = std::min(minConf, bestScore);
    }

    res.rawDigits = digits;
    res.avgConfidence = sumConf / 14.0;
    res.minConfidence = minConf;

    const auto parsedMs = TimeUtils::parseDateTimeString(digits, tzOffsetSec);
    if (!parsedMs.has_value()) {
        return res;
    }

    // 合理年份 sanity check (2020-2035) 与置信度门槛
    const int yr = digits.left(4).toInt();
    if (yr < 2020 || yr > 2035 || res.avgConfidence < 0.65 || res.minConfidence < 0.42) {
        return res;
    }

    res.ok = true;
    res.detectedWallMs = *parsedMs;
    res.formattedText = TimeUtils::formatEpochMs(*parsedMs, tzOffsetSec);
    return res;
}

OcrResult TimestampOcr::recognizeFromFrame(const DecodedFrame& frame, int tzOffsetSec) {
    if (!frame.nv12Data || frame.nv12Data->empty()) return {};
    return recognizeFromYPlane(frame.nv12Data->data(), frame.width, frame.height, frame.yStride, tzOffsetSec);
}

