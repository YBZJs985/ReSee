struct NormalizedTemplates {
    std::array<std::array<float, kTplLen>, 10> tpl;
    NormalizedTemplates() {
        for (int d = 0; d < 10; ++d) {
            double sum = 0.0;
            for (int i = 0; i < kTplLen; ++i) sum += kDigitTemplates[d][i];
            const double mean = sum / kTplLen;
            double sq = 0.0;
            for (int i = 0; i < kTplLen; ++i) {
                const double v = kDigitTemplates[d][i] - mean;
                tpl[d][i] = static_cast<float>(v);
                sq += v * v;
            }
            const float invNorm = static_cast<float>(1.0 / (std::sqrt(sq) + 1e-6));
            for (int i = 0; i < kTplLen; ++i) {
                tpl[d][i] *= invNorm;
            }
        }
    }
};

const NormalizedTemplates& getTemplates() {
    static const NormalizedTemplates inst;
    return inst;
}

float scorePatch(const uint8_t* yPlane, int yStride, int x0, int y0, int bw, int bh,
                 const std::array<float, kTplLen>& tpl) {
    std::array<float, kTplLen> patch{};
    double sum = 0.0;
    for (int ty = 0; ty < kTplH; ++ty) {
        const float sy = (static_cast<float>(ty) + 0.5f) * static_cast<float>(bh) / static_cast<float>(kTplH) - 0.5f;
        const int iy0 = std::clamp(static_cast<int>(std::floor(sy)), 0, bh - 1);
        const int iy1 = std::min(iy0 + 1, bh - 1);
        const float fy = std::max(0.0f, sy - static_cast<float>(iy0));
        const uint8_t* row0 = yPlane + static_cast<size_t>(y0 + iy0) * yStride + x0;
        const uint8_t* row1 = yPlane + static_cast<size_t>(y0 + iy1) * yStride + x0;
        for (int tx = 0; tx < kTplW; ++tx) {
            const float sx = (static_cast<float>(tx) + 0.5f) * static_cast<float>(bw) / static_cast<float>(kTplW) - 0.5f;
            const int ix0 = std::clamp(static_cast<int>(std::floor(sx)), 0, bw - 1);
            const int ix1 = std::min(ix0 + 1, bw - 1);
            const float fx = std::max(0.0f, sx - static_cast<float>(ix0));
            const float v00 = row0[ix0], v10 = row0[ix1], v01 = row1[ix0], v11 = row1[ix1];
            const float val = (v00 * (1.0f - fx) + v10 * fx) * (1.0f - fy) +
                              (v01 * (1.0f - fx) + v11 * fx) * fy;
            const int idx = ty * kTplW + tx;
            patch[idx] = val;
            sum += val;
        }
    }
    const float mean = static_cast<float>(sum / kTplLen);
    double sq = 0.0;
    double dot = 0.0;
    for (int i = 0; i < kTplLen; ++i) {
        const float v = patch[i] - mean;
        sq += static_cast<double>(v) * v;
        dot += static_cast<double>(v) * tpl[i];
    }
    return static_cast<float>(dot / (std::sqrt(sq) + 1e-6));
}

